import { readFileSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

/**
 * The watermark, in pixels of every delivered image (whatever its size, from
 * the 480 px placeholder to the original): the LN mark (public/watermark.svg),
 * `width` px wide, rotated `angle` degrees and repeated as a grid with `gap` px
 * of empty space between the edges of neighboring marks, at `opacity` %. The
 * sizes are exact inside the file; on screen they scale with the photo.
 *
 * After changing them, run `pnpm cloudinary:setup --force`: it rebuilds the
 * tile (scripts/cloudinary/watermark.svg), uploads it and regenerates the photos.
 */
export const WATERMARK = { width: 40, gap: 200, angle: -30, opacity: 5 };

const MARK_FILE = new URL('../../public/watermark.svg', import.meta.url);

export const TILE_FILE = fileURLToPath(new URL('./watermark.svg', import.meta.url));

/**
 * Points on the outline of every path of the mark (absolute M, L, H, V, C and
 * Z commands, the only ones the file uses), with each curve sampled, so the
 * size is the drawing's own, not the SVG's box (which has a wide margin).
 */
const markPoints = svg => {
  const points = [];

  for (const [, d] of svg.matchAll(/ d="([^"]+)"/g)) {
    const tokens = d.match(/[MLHVCZ]|-?\d*\.?\d+(?:e-?\d+)?/gi) ?? [];
    let x = 0;
    let y = 0;
    let command = '';
    let i = 0;
    const next = () => Number(tokens[i++]);

    while (i < tokens.length) {
      if (/[A-Z]/i.test(tokens[i])) command = tokens[i++].toUpperCase();

      if (command === 'Z') continue;

      if (command === 'M' || command === 'L') {
        x = next();
        y = next();
      } else if (command === 'H') {
        x = next();
      } else if (command === 'V') {
        y = next();
      } else if (command === 'C') {
        const [x1, y1, x2, y2, x3, y3] = [next(), next(), next(), next(), next(), next()];

        for (let t = 0.125; t < 1; t += 0.125) {
          const u = 1 - t;

          points.push([
            u ** 3 * x + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t ** 3 * x3,
            u ** 3 * y + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t ** 3 * y3,
          ]);
        }

        x = x3;
        y = y3;
      } else {
        throw new Error(`Unsupported path command in public/watermark.svg: ${command}`);
      }

      points.push([x, y]);
    }
  }

  return points;
};

const bounds = points => {
  const xs = points.map(p => p[0]);
  const ys = points.map(p => p[1]);

  return { minX: Math.min(...xs), maxX: Math.max(...xs), minY: Math.min(...ys), maxY: Math.max(...ys) };
};

/**
 * The tile's geometry: the scale of the mark (pixels per SVG unit), its size
 * once rotated, and the tile, which is that size plus the gap on each axis.
 */
export const watermarkGeometry = () => {
  const svg = readFileSync(MARK_FILE, 'utf8');
  const points = markPoints(svg);
  const flat = bounds(points);
  const scale = WATERMARK.width / (flat.maxX - flat.minX);
  const radians = (WATERMARK.angle * Math.PI) / 180;
  const rotated = bounds(
    points.map(([x, y]) => [
      x * Math.cos(radians) - y * Math.sin(radians),
      x * Math.sin(radians) + y * Math.cos(radians),
    ]),
  );
  const markWidth = (rotated.maxX - rotated.minX) * scale;
  const markHeight = (rotated.maxY - rotated.minY) * scale;

  return {
    svg,
    scale,
    rotated,
    mark: { width: markWidth, height: markHeight },
    tile: { width: Math.round(markWidth + WATERMARK.gap), height: Math.round(markHeight + WATERMARK.gap) },
  };
};

/** Writes scripts/cloudinary/watermark.svg: the rotated mark centered in its tile, sized in pixels. */
export const buildWatermarkTile = async () => {
  const { svg, scale, rotated, tile } = watermarkGeometry();
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).trim();
  const viewWidth = tile.width / scale;
  const viewHeight = tile.height / scale;
  // Rotate the mark, then move the center of its rotated outline to the center of the tile.
  const dx = viewWidth / 2 - (rotated.minX + rotated.maxX) / 2;
  const dy = viewHeight / 2 - (rotated.minY + rotated.maxY) / 2;
  const round = n => Math.round(n * 100) / 100;
  const out = `<svg xmlns="http://www.w3.org/2000/svg" width="${tile.width}" height="${tile.height}" viewBox="0 0 ${round(viewWidth)} ${round(viewHeight)}" fill="none">
<!-- Generated by scripts/cloudinary/watermark.mjs from public/watermark.svg: the LN mark ${WATERMARK.width} px wide, rotated ${WATERMARK.angle}°, ${WATERMARK.gap} px between repetitions. Do not edit by hand. -->
<g transform="translate(${round(dx)} ${round(dy)}) rotate(${WATERMARK.angle})">
${inner}
</g>
</svg>
`;

  await writeFile(TILE_FILE, out);

  return { file: TILE_FILE, ...tile };
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { file, width, height } = await buildWatermarkTile();

  // eslint-disable-next-line no-console -- CLI usage
  console.log(`✓ ${file}: ${width} × ${height} px`);
}
